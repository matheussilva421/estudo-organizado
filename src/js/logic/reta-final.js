function deepClone(value) {
  return JSON.parse(JSON.stringify(value));
}

/** Commit a validated editor draft, then publish memory and save notifications. */
export function commitRetaFinalDraft(options = {}) {
  const sourceContext = options.context || {};
  return commitRetaFinalDraftToStore({
    ...options,
    db: options.db || storeDb,
    context: {
      today: todayStr(),
      now: new Date().toISOString(),
      makeId: () => uid(),
      ...sourceContext,
    },
  });
}

function isRetaFinalPlan(plan = state.planejamento) {
  return Boolean(plan?.ativo && plan.tipo === 'reta_final' && plan.retaFinal);
}

/**
 * Blocos já consumidos por eventos preservados (sessão estudada ou com tempo
 * acumulado). O agendador não pode re-materializar nem rolar esses blocos —
 * análogo exato do occupiedSlots do Ciclo (bug histórico da "sessão que
 * volta", commit 8756f10).
 * @returns {Set<string>}
 */
export function getRetaFinalOccupiedBlocoIds(eventos = state.eventos) {
  const occupied = new Set();
  for (const ev of eventos || []) {
    if (!ev?.rfBlocoId) continue;
    if (ev.status === 'estudei' || Number(ev.tempoAcumulado) > 0 || ev._timerStart) {
      occupied.add(ev.rfBlocoId);
    }
  }
  return occupied;
}

/** Ids com evidência real de estudo (não timer parcial). */
function getRetaFinalCompletedBlocoIds(eventos = state.eventos) {
  const completed = new Set();
  for (const ev of eventos || []) {
    if (ev?.rfBlocoId && ev.status === 'estudei') completed.add(ev.rfBlocoId);
  }
  return completed;
}

function isPreservedEvent(ev) {
  return ev.status === 'estudei' || Number(ev.tempoAcumulado) > 0 || Boolean(ev._timerStart);
}

function applyImportedNotesToEvent(ev, bloco) {
  if (typeof bloco?.notas !== 'string') return false;
  if (!ev.isAutoGenerated && ev.rfNotasAutomaticas === undefined) return false;

  let changed = false;
  const previousAutomaticNotes = ev.rfNotasAutomaticas;
  if (typeof previousAutomaticNotes === 'string' && ev.notas === previousAutomaticNotes) {
    if (ev.notas === bloco.notas) return false;
    ev.notas = bloco.notas;
    ev.rfNotasAutomaticas = bloco.notas;
    ev.updatedAt = new Date().toISOString();
    return true;
  }

  if (previousAutomaticNotes !== undefined) {
    delete ev.rfNotasAutomaticas;
    changed = true;
  }
  if (typeof ev.notas === 'string') return changed;

  ev.notas = bloco.notas;
  ev.rfNotasAutomaticas = bloco.notas;
  ev.updatedAt = new Date().toISOString();
  return true;
}

function importedNotesFields(bloco) {
  return typeof bloco?.notas === 'string'
    ? { notas: bloco.notas, rfNotasAutomaticas: bloco.notas }
    : {};
}

/**
 * Agendador idempotente da Reta Final (chamado no boot, no render da view e
 * roteado por syncCicloToEventos quando tipo === 'reta_final'):
 *  1. projeta blocos v2 a partir da intenção (ou reconcilia/rola o legado v1);
 *  2. mantém `bloco.data` como projeção compatível, sem tocar dataPlanejada;
 *  3. remove autos órfãos não preservados (bloco sumiu/rolou/concluiu);
 *  4. materializa eventos para blocos pendentes de hoje/futuro sem evento.
 * Nunca chama touchPlanejamento(): rolagem/projeção/reconcile são views
 * derivadas, re-deriváveis em cada dispositivo (anti ping-pong LWW).
 */
export function syncRetaFinalToEventos() {
  if (!isRetaFinalPlan()) return;
  const plan = state.planejamento;
  const retaFinal = plan.retaFinal;
  const today = todayStr();

  const occupied = getRetaFinalOccupiedBlocoIds(state.eventos);
  const blocoById = new Map();
  for (const bloco of retaFinal.blocos || []) {
    if (bloco?.id) blocoById.set(bloco.id, bloco);
  }

  const isV2 = plan.schemaVersionRetaFinal === 2;
  let derivedChanged = false;
  let blocksForEvents = retaFinal.blocos || [];

  if (isV2) {
    const projection = projectRetaFinalSchedule(plan, {
      today,
      occupiedBlocoIds: occupied,
      completedBlocoIds: getRetaFinalCompletedBlocoIds(state.eventos)
    });
    blocksForEvents = projection.blocos;
    const rolledIds = new Set();
    for (const projected of projection.blocos) {
      if (!projected?.id) continue;
      const bloco = blocoById.get(projected.id);
      if (!bloco || bloco.arquivado === true) continue;
      const compatData = projected.dataEfetiva || bloco.data;
      const dataRolou = bloco.data !== compatData;
      if (dataRolou) {
        bloco.data = compatData;
        derivedChanged = true;
      }
      if (dataRolou && projected.rolado === true) {
        bloco.rolagens = (Number(bloco.rolagens) || 0) + 1;
        rolledIds.add(bloco.id);
      }
      if (bloco.status !== projected.status) {
        bloco.status = projected.status;
        derivedChanged = true;
      }
    }
    if (rolledIds.size > 0) {
      const fixos = retaFinal.blocos.filter((bloco) => !rolledIds.has(bloco?.id));
      let insertAt = 0;
      for (let index = 0; index < fixos.length; index += 1) {
        if (fixos[index]?.data && fixos[index].data <= today) insertAt = index + 1;
      }
      const movidos = retaFinal.blocos.filter((bloco) => rolledIds.has(bloco?.id));
      retaFinal.blocos = [
        ...fixos.slice(0, insertAt),
        ...movidos,
        ...fixos.slice(insertAt),
      ];
      derivedChanged = true;
    }
  } else {
    const reconcile = reconcileRetaFinalWithEvents(plan, state.eventos);
    const rollover = rolloverRetaFinalBlocks(retaFinal, {
      today,
      preservedBlocoIds: occupied
    });
    derivedChanged = reconcile.changed || rollover.changed;
  }

  // 3. Reconstrói autos a partir do cronograma efetivo. Título e timestamp
  // continuam no wrapper por dependerem do catálogo e do relógio local.
  const rebuild = rebuildRetaFinalAutoEvents(
    { ...plan, retaFinal: { ...retaFinal, blocos: blocksForEvents } },
    state.eventos,
    { today, makeId: () => uid(), now: new Date().toISOString() }
  );
  const carriedNotes = carryRemovedAutoNotesToBlocks(
    retaFinal.blocos,
    rebuild.diagnostics.removed
  );
  if (carriedNotes > 0) {
    // Conteúdo humano movido do evento para o bloco é mutação real: precisa de
    // nova revisão para o descritor de sync não rejeitar digest diferente.
    plan.revision = (Number(plan.revision) || 0) + 1;
    plan.updatedAt = new Date().toISOString();
    derivedChanged = true;
  }
  state.eventos = rebuild.events;
  const createdEventIds = new Set(rebuild.diagnostics.created.map((item) => item.eventId));

  for (const ev of state.eventos) {
    if (!createdEventIds.has(ev?.id)) continue;
    const bloco = blocoById.get(ev.rfBlocoId);
    if (!bloco) continue;
    ev.titulo = buildRetaFinalEventTitle(bloco, findDisciplina(bloco.discId));
    ev.criadoEm = new Date().toISOString();
  }


  // 3b. Hidrata eventos legados sem nota e atualiza somente texto ainda
  // reconhecível como importado. Edições manuais, inclusive texto apagado,
  // deixam de ser gerenciadas pelo JSON.
  let notesUpdated = 0;
  for (const ev of state.eventos) {
    if (!ev?.rfBlocoId) continue;
    const bloco = blocoById.get(ev.rfBlocoId);
    if (bloco && applyImportedNotesToEvent(ev, bloco)) notesUpdated++;
  }

  // 3c. Retítulo dos autos sustentados com título obsoleto (ex.: eventos
  // criados antes do título com tópico). Determinístico e re-derivado por
  // dispositivo — nunca carimba ev.updatedAt (anti ping-pong LWW). Eventos
  // preservados (estudei/com tempo) já saíram no isPreservedEvent acima.
  let retitled = 0;
  for (const ev of state.eventos) {
    if (!ev?.rfBlocoId || !ev.isAutoGenerated || isPreservedEvent(ev)) continue;
    const bloco = blocoById.get(ev.rfBlocoId);
    if (!bloco) continue;
    const titulo = buildRetaFinalEventTitle(bloco, findDisciplina(bloco.discId));
    if (ev.titulo !== titulo) {
      ev.titulo = titulo;
      retitled++;
    }
  }

  if (derivedChanged || rebuild.changed || retitled > 0 || notesUpdated > 0 || carriedNotes > 0) {

    scheduleSave();
  }
}

/**
 * "Marcar como estudado" com um clique num bloco pendente: promove o evento
 * auto 'agendado' do bloco para 'estudei' (preservando tempoAcumulado), ou
 * cria um se não existir. A conclusão do bloco continua derivada de eventos —
 * o reconcile dentro de syncRetaFinalToEventos fecha o bloco. Mutação real do
 * usuário: carimba ev.updatedAt (LWW), mas nunca planejamento.updatedAt.
 * Não mexe em hábitos/revisões/aula.estudada — detalhes de tempo/questões são
 * complementados depois editando a sessão no Histórico (edit-session-record).
 * Undo = excluir/editar a sessão no Histórico (reconcile reabre o bloco).
 * @returns {boolean} true se marcou
 */
export function quickCompleteRetaFinalBloco(blocoId) {
  if (!isRetaFinalPlan()) return false;
  const bloco = (state.planejamento.retaFinal.blocos || []).find((b) => b?.id === blocoId);
  if (!bloco || bloco.status !== 'pendente') return false;

  let ev = (state.eventos || []).find((e) => e?.rfBlocoId === blocoId && e.status === 'agendado');
  if (!ev) {
    ev = {
      id: 'autorf_' + uid(),
      titulo: '',
      data: bloco.data,
      duracao: Math.max(0, Math.round(Number(bloco.minutos) || 0)),
      status: 'agendado',
      tempoAcumulado: 0,
      tipo: 'conteudo',
      discId: bloco.discId || null,
      assId: null,
      aulaId: null,
      habito: null,
      ...importedNotesFields(bloco),
      rfBlocoId: bloco.id,
      criadoEm: new Date().toISOString(),
      isAutoGenerated: true
    };
    state.eventos.push(ev);
  }

  ev.titulo = buildRetaFinalEventTitle(bloco, findDisciplina(bloco.discId));
  ev.status = 'estudei';
  ev.dataEstudo = todayStr();
  const topicos = buildTopicosFromRetaFinalBloco(bloco).map((item) => ({
    ...item,
    statusTopico: 'em_andamento'
  }));
  applyTopicosToEvent(ev, topicos);
  ev.updatedAt = new Date().toISOString();

  syncRetaFinalToEventos();
  scheduleSave();
  return true;
}

/**
 * Garante e devolve o evento 'agendado' espelhado de um bloco pendente, para
 * iniciar o cronômetro a partir do Foco de Hoje / cronograma. "Ensure" porque
 * MUTA estado: roda o sync antes — um bloco atrasado é rolado para hoje e
 * materializado na hora —, então o retorno é sempre um evento pronto para
 * toggleTimer (ou null se o bloco não é cronometrável — concluído, não
 * coberto, inexistente ou plano não reta_final).
 * @returns {object|null} o evento espelhado
 */
export function ensureRetaFinalBlocoEvento(blocoId) {
  if (!isRetaFinalPlan()) return null;
  const bloco = (state.planejamento.retaFinal.blocos || []).find((b) => b?.id === blocoId);
  if (!bloco || bloco.status !== 'pendente') return null;
  syncRetaFinalToEventos();
  return (state.eventos || []).find((e) => e?.rfBlocoId === blocoId && e.status === 'agendado') || null;
}

/**
 * Associa uma sessão do Histórico (evento `estudei` sem vínculo) a um bloco
 * pendente: seta `rfBlocoId` e o reconcile conclui o bloco. Preserva a DATA
 * REAL da sessão (não toca data/dataEstudo) — é o caminho para blocos
 * atrasados/"rolados" já estudados por fora. O auto 'agendado' órfão do bloco
 * é limpo pelo wipe do sync, sem tombstone (autos são re-deriváveis).
 * Mutação real do usuário: carimba ev.updatedAt; nunca planejamento.updatedAt.
 * @returns {boolean} true se associou
 */
export function associateHistoryEventToBloco(blocoId, eventoId) {
  if (!isRetaFinalPlan()) return false;
  const bloco = (state.planejamento.retaFinal.blocos || []).find((b) => b?.id === blocoId);
  if (!bloco || bloco.status !== 'pendente') return false;
  const ev = (state.eventos || []).find((e) => e?.id === eventoId);
  if (!ev || ev.status !== 'estudei' || ev.rfBlocoId) return false;

  ev.rfBlocoId = bloco.id;
  ev.updatedAt = new Date().toISOString();

  syncRetaFinalToEventos();
  scheduleSave();
  return true;
}

/**
 * Remove eventos pendentes derivados de qualquer plano (autos do Ciclo, com
 * seqId ou com rfBlocoId), preservando estudados e com tempo acumulado —
 * mesmo critério de resetCicloAndWipeEvents. Usado na troca de plano
 * (ativação/restauração da Reta Final).
 */
function wipeAutoPlanEvents(preservedRetaFinalBlockIds = new Set()) {
  state.eventos = (state.eventos || []).filter((ev) => {
    const isPlanned = ev?.isAutoGenerated || Boolean(ev?.seqId) || Boolean(ev?.rfBlocoId);
    if (!isPlanned) return true;
    if (ev?.rfBlocoId && preservedRetaFinalBlockIds.has(ev.rfBlocoId)) return true;
    return isPreservedEvent(ev);
  });
}

function findDisciplina(discId, editais = state.editais) {
  for (const edital of editais || []) {
    for (const disc of edital?.disciplinas || []) {
      if (disc.id === discId) return disc;
    }
  }
  return null;
}

function payloadBlockIdentity(data, bloco) {
  const topicos = [];
  for (const nome of Array.isArray(bloco?.topicos) ? bloco.topicos : []) {
    const key = normalizeNameKey(nome);
    if (key) topicos.push(['assunto', key]);
  }
  const aulaKey = normalizeNameKey(bloco?.aula);
  if (aulaKey) topicos.push(['aula', aulaKey]);
  return JSON.stringify([String(data || ''), normalizeNameKey(bloco?.disciplina), topicos]);
}

function storedBlockIdentity(bloco) {
  const disciplina = findDisciplina(bloco?.discId);
  const topicos = [];
  for (const topico of bloco?.topicos || []) {
    if (topico?.assId) {
      const assunto = (disciplina?.assuntos || []).find((item) => item?.id === topico.assId);
      topicos.push(['assunto', normalizeNameKey(assunto?.nome || `id:${topico.assId}`)]);
    }
    if (topico?.aulaId) {
      const aula = (disciplina?.aulas || []).find((item) => item?.id === topico.aulaId);
      topicos.push(['aula', normalizeNameKey(aula?.nome || `id:${topico.aulaId}`)]);
    }
  }
  return JSON.stringify([
    String(bloco?.dataOriginal || bloco?.data || ''),
    normalizeNameKey(disciplina?.nome || `id:${bloco?.discId || ''}`),
    topicos,
  ]);
}

function hasReimportData(bloco, eventos) {
  if (
    (bloco?.status && bloco.status !== 'pendente') ||
    Number(bloco?.rolagens) > 0 ||
    (bloco?.dataOriginal && bloco.data !== bloco.dataOriginal) ||
    Object.prototype.hasOwnProperty.call(bloco || {}, 'notas')
  ) {
    return true;
  }

  return (eventos || []).some((ev) => {
    if (ev?.rfBlocoId !== bloco?.id) return false;
    return (
      !ev.isAutoGenerated ||
      ev.status === 'estudei' ||
      Number(ev.tempoAcumulado) > 0 ||
      Boolean(ev._timerStart) ||
      Boolean(ev.updatedAt) ||
      Boolean(ev.dataEstudo) ||
      Boolean(ev.sessao && Object.keys(ev.sessao).length > 0) ||
      ev.notas !== undefined ||
      ev.rfNotasAutomaticas !== undefined ||
      Boolean(ev.fontes) ||
      Boolean(ev.legislacao)
    );
  });
}

function prepareReimportEntries(payload, currentPlan) {
  const days = [...payload.dias].sort((a, b) => (a.data < b.data ? -1 : a.data > b.data ? 1 : 0));
  const entries = days.flatMap((dia) =>
    (dia.blocos || []).map((blocoPayload) => ({
      dia,
      blocoPayload,
      key: payloadBlockIdentity(dia.data, blocoPayload),
      previousBlock: null,
    }))
  );
  const previousBlocks =
    currentPlan?.ativo && currentPlan.tipo === 'reta_final'
      ? currentPlan.retaFinal?.blocos || []
      : [];
  if (!previousBlocks.length) return entries;

  const eventos = [...(state.eventos || []), ...(state.arquivo || [])];
  const previousByKey = new Map();
  for (const bloco of previousBlocks) {
    const key = storedBlockIdentity(bloco);
    if (!previousByKey.has(key)) previousByKey.set(key, []);
    previousByKey.get(key).push(bloco);
  }
  const incomingCounts = new Map();
  for (const entry of entries) incomingCounts.set(entry.key, (incomingCounts.get(entry.key) || 0) + 1);

  for (const [key, previous] of previousByKey) {
    if (previous.length > 1 && previous.some((bloco) => hasReimportData(bloco, eventos))) {
      throw new Error(
        'Reimportação cancelada para preservar dados: há blocos com identidade ambígua e progresso, notas ou histórico associados.'
      );
    }
    if (
      previous.length !== (incomingCounts.get(key) || 0) &&
      previous.some((bloco) => hasReimportData(bloco, eventos))
    ) {
      throw new Error(
        'Reimportação cancelada para preservar notas, progresso, timers e histórico: a quantidade de blocos com a mesma identidade mudou.'
      );
    }
  }

  const queues = new Map([...previousByKey].map(([key, blocks]) => [key, [...blocks]]));
  const matchedIds = new Set();
  for (const entry of entries) {
    const previousBlock = queues.get(entry.key)?.shift() || null;
    if (previousBlock) {
      entry.previousBlock = previousBlock;
      if (previousBlock.id) matchedIds.add(previousBlock.id);
    }
  }

  const unmatched = previousBlocks.filter(
    (bloco) => hasReimportData(bloco, eventos) && (!bloco.id || !matchedIds.has(bloco.id))
  );
  if (unmatched.length) {
    throw new Error(
      `Reimportação cancelada para preservar notas, progresso, timers e histórico: ${unmatched.length} bloco(s) não têm correspondência segura no novo JSON.`
    );
  }
  return entries;
}

/**
 * Ativa a Reta Final a partir de um payload validado:
 *  1. cria disciplinas/assuntos/aulas faltantes nos editais (disciplina nova
 *     vai no edital principal ativo, ou num edital "Reta Final" se não houver);
 *  2. arquiva o plano ativo em state.planejamentoArquivado (restaurável após a
 *     dataFinal); re-import sobre uma reta_final preserva o arquivado original;
 *  3. substitui state.planejamento por um plano tipo 'reta_final' com os
 *     blocos dia-a-dia (updatedAt novo: import é mutação real do usuário, ao
 *     contrário da rolagem);
 *  4. limpa autos pendentes do plano anterior e materializa os novos eventos.
 * @param {{ payload: object, matching?: object }} params - matching opcional
 *   (resultado de matchRetaFinalToEditais usado no preview); recalculado se
 *   ausente.
 * @returns {object} o novo state.planejamento
 */
export function activateRetaFinal({ payload, matching } = {}) {
  const validation = validateRetaFinalPayload(payload);
  if (!validation.valid) {
    throw new Error('JSON da Reta Final inválido: ' + validation.errors.join(' '));
  }
  const match = matching || matchRetaFinalToEditais(payload, state.editais);
  const reimportEntries = prepareReimportEntries(payload, state.planejamento);

  // 1. Prepara um working set: o estado real só recebe os editais depois que
  // a migração v2 for validada, preservando as identidades do cache.
  const workingEditais = Array.isArray(state.editais) ? deepClone(state.editais) : [];
  let targetEdital = workingEditais.find((e) => e && !e.arquivado) || null;
  const ensureTargetEdital = () => {
    if (!targetEdital) {
      targetEdital = {
        id: uid(),
        nome: 'Reta Final',
        cor: '#0f766e',
        disciplinas: [],
        arquivado: false,
        arquivadoEm: null
      };
      workingEditais.push(targetEdital);
    }
    return targetEdital;
  };

  const resolvedByKey = new Map(); // key da disciplina -> { discId, assIdByKey, aulaIdByKey }
  for (const discMatch of match.disciplinas) {
    let disc = discMatch.discId ? findDisciplina(discMatch.discId, workingEditais) : null;
    if (!disc) {
      const edital = ensureTargetEdital();
      disc = {
        id: uid(),
        nome: discMatch.nome,
        icone: '📚',
        cor: edital.cor || '#0f766e',
        assuntos: [],
        aulas: []
      };
      edital.disciplinas.push(disc);
    }
    if (!Array.isArray(disc.assuntos)) disc.assuntos = [];
    if (!Array.isArray(disc.aulas)) disc.aulas = [];

    const assIdByKey = new Map();
    for (const topico of discMatch.topicos) {
      let assId = topico.assId;
      if (!assId) {
        const assunto = {
          id: 'ass_' + uid(),
          nome: topico.nome,
          concluido: false,
          dataConclusao: null,
          revisoesFetas: [],
          adiamentos: 0,
          linkedAulaIds: []
        };
        disc.assuntos.push(assunto);
        assId = assunto.id;
      }
      assIdByKey.set(topico.key, assId);
    }

    const aulaIdByKey = new Map();
    for (const aulaMatch of discMatch.aulas) {
      let aulaId = aulaMatch.aulaId;
      if (!aulaId) {
        const aula = {
          id: 'aula_' + uid(),
          nome: aulaMatch.nome,
          descricao: '',
          estudada: false,
          dataEstudo: null,
          progress: 0,
          linkedAssuntoIds: []
        };
        disc.aulas.push(aula);
        aulaId = aula.id;
      }
      aulaIdByKey.set(aulaMatch.key, aulaId);
    }

    resolvedByKey.set(discMatch.key, {
      discId: disc.id,
      assIdByKey,
      aulaIdByKey
    });
  }

  // 2. Monta os blocos dia-a-dia (ordem estável por data).
  const minutosPadrao =
    Number.isInteger(payload.minutosPadrao) && payload.minutosPadrao > 0 ? payload.minutosPadrao : 60;
  const blocos = [];
  for (const entry of reimportEntries) {
    const { dia, blocoPayload, previousBlock } = entry;
    const resolved = resolvedByKey.get(normalizeNameKey(blocoPayload.disciplina));
    if (!resolved) continue;
    const topicos = [];
    for (const topicoNome of Array.isArray(blocoPayload.topicos) ? blocoPayload.topicos : []) {
      const assId = resolved.assIdByKey.get(normalizeNameKey(topicoNome));
      if (assId) topicos.push({ assId, aulaId: null });
    }
    const aulaId = resolved.aulaIdByKey.get(normalizeNameKey(blocoPayload.aula));
    if (aulaId) topicos.push({ assId: null, aulaId });
    const bloco = {
      ...(previousBlock || {}),
      id: previousBlock?.id || 'rf_' + uid(),
      data: previousBlock?.data || dia.data,
      dataOriginal: dia.data,
      discId: resolved.discId,
      topicos,
      minutos:
        Number.isInteger(blocoPayload.minutos) && blocoPayload.minutos > 0
          ? blocoPayload.minutos
          : minutosPadrao,
      status: previousBlock?.status || 'pendente',
      rolagens: Number(previousBlock?.rolagens) || 0,
    };
    if (typeof blocoPayload.notas === 'string') bloco.notas = blocoPayload.notas;
    blocos.push(bloco);
  }

  // 3. Arquiva o plano ativo e substitui pelo plano reta_final. Se o plano
  // atual já é uma reta_final (re-import), o arquivado original (pré-reta)
  // é preservado — arquivar a reta antiga o perderia.
  const now = new Date().toISOString();
  const current = state.planejamento;
  const archived =
    current?.ativo && current.tipo && current.tipo !== 'reta_final'
      ? { plan: deepClone(current), arquivadoEm: now }
      : null;

  const candidatePlan = {
    ativo: true,
    tipo: 'reta_final',
    disciplinas: [...new Set(blocos.map((b) => b.discId))],
    relevancia: {},
    horarios: { dataFinal: payload.dataFinal },
    materiasPorDia: state.config?.materiasPorDia || 3,
    sequencia: [],
    skippedSlots: [],
    slotOverrides: [],
    ciclosCompletos: 0,
    dataInicioCicloAtual: now,
    // Import é mutação real do usuário: reivindica autoria no LWW do plano
    // (equivalente a touchPlanejamento(); não importado de cycle.js para não
    // criar ciclo de imports).
    updatedAt: now,
    retaFinal: {
      nome: String(payload.nome || 'Reta Final'),
      dataFinal: payload.dataFinal,
      minutosPadrao,
      importadoEm: now,
      blocos
    }
  };

  // Allocate lineage and validate before replacing state or touching events.
  const migration = migrateRetaFinalV2(candidatePlan, {
    makePlanId: () => 'rfplan_' + uid()
  });
  if (!migration.changed || migration.plan?.schemaVersionRetaFinal !== 2 || !migration.plan?.planId) {
    const detail = migration.diagnostics?.length
      ? migration.diagnostics.join(' ')
      : 'migração não produziu um plano v2 válido.';
    throw new Error('Falha ao migrar a Reta Final para v2: ' + detail);
  }

  state.editais = workingEditais;
  if (archived) state.planejamentoArquivado = archived;
  state.planejamento = migration.plan;

  // 4. Troca de plano: limpa autos pendentes do plano anterior e materializa.
  const preservedBlockIds = new Set(
    reimportEntries.map((entry) => entry.previousBlock?.id).filter(Boolean)
  );
  wipeAutoPlanEvents(preservedBlockIds);
  syncRetaFinalToEventos();
  scheduleSave();
  return state.planejamento;
}

/**
 * Restaura o plano arquivado pela ativação da Reta Final (banner pós-prova).
 * Restauração é mutação real: reivindica autoria no LWW (updatedAt novo) para
 * propagar entre dispositivos. O chamador (camada de ações) deve invalidar
 * caches e re-agendar eventos do plano restaurado (syncCicloToEventos).
 * @returns {boolean} true se restaurou
 */
export function restaurarPlanejamentoArquivado() {
  const arquivado = state.planejamentoArquivado;
  if (!arquivado?.plan) return false;
  const plan = deepClone(arquivado.plan);
  plan.updatedAt = new Date().toISOString();
  state.planejamento = plan;
  state.planejamentoArquivado = null;
  wipeAutoPlanEvents();
  scheduleSave();
  return true;
}
