// =============================================
// RETA FINAL — ORQUESTRAÇÃO (estado + agendador)
// Camada com estado sobre o núcleo puro (reta-final-core.js): materializa os
// blocos do cronograma dia-a-dia como eventos do calendário (rfBlocoId,
// análogo ao seqId do Ciclo). Importada por logic/cycle.js (roteamento de
// syncCicloToEventos) — por isso este módulo só importa store/utils/core,
// nunca cycle.js (evita ciclo de imports).
// =============================================
