export function skipPlanejamentoEventBeforeDelete(eventToDelete) {
  if (!eventToDelete?.seqId || !state.planejamento?.sequencia) return false;
  if (eventToDelete.status === 'estudei') return false;

  const seq = state.planejamento.sequencia.find((item) => item.id === eventToDelete.seqId);
  if (!seq || !isPlanejamentoSeqPending(seq)) return false;

  // Excluir a sessão registra a perda do SLOT (data#slotIndex) em
  // slotOverrides: só aquela vaga deixa de ser reagendada; a etapa continua
  // pendente e a matéria volta em slots futuros da rotação. Diferente do
  // skippedSlots legado, o override persiste independente do ciclo de vida do
  // evento (regen da janela, virada do dia, timer parcial). skippedSlots de
  // versões antigas continuam respeitados na leitura (syncCicloToEventos).
  upsertSlotOverride({
    data: eventToDelete.data || todayStr(),
    slotIndex: Number(eventToDelete.slotIndex) || 0,
    seqId: eventToDelete.seqId,
    status: 'perdido',
    originalDiscId: eventToDelete.discId || seq.discId,
    sourceEventId: eventToDelete.id,
  });

  return true;
}

export function substitutePlanejamentoSlot(slotEvent, actualEvent) {
  if (!slotEvent?.seqId || !actualEvent?.id || !state.planejamento?.sequencia) return null;
  const seq = state.planejamento.sequencia.find((item) => item.id === slotEvent.seqId);
  return upsertSlotOverride({
    data: slotEvent.data || actualEvent.data || todayStr(),
    slotIndex: Number(slotEvent.slotIndex) || 0,
    seqId: slotEvent.seqId,
    status: 'substituido',
    originalDiscId: slotEvent.discId || seq?.discId || null,
    actualDiscId: actualEvent.discId || null,
    actualEventId: actualEvent.id,
    sourceEventId: slotEvent.id,
  });
}

export function calculateCyclePredictionsModel(startDateStr, endDateStr) {
  if (
    !state.planejamento ||
    !state.planejamento.sequencia ||
    state.planejamento.sequencia.length === 0
  )
    return {};

  const start = new Date(startDateStr + 'T00:00:00');
  const end = new Date(endDateStr + 'T23:59:59');
  if (isNaN(start) || isNaN(end) || start > end) return {};

  const seq = getPendingPlanejamentoSequence();
  if (seq.length === 0) return {};
  const materiasPorDia = getPlanMateriasPorDia(state.planejamento);
  const activeDaysFilter = getActiveStudyDaysFilter(state.planejamento);
  const skippedSlots = getSkippedSlotKeySet(state.planejamento);
  const slotOverrides = getSlotOverrideMap(state.planejamento);
  const occupiedSlots = getOccupiedSlotKeySet(state.eventos);
  let simulatedIdx = 0;

  // Fonte única de progresso: mesma distribuição usada pela barra da Sequência
  // e pelo agendador (todo estudo da disciplina conta, inclusive Sessão Livre).
  const remBySeq = getCycleProgress(state.planejamento);
  const firstVisit = new Set();

  const projection = {};

  for (let d = new Date(start); d <= end; d.setDate(d.getDate() + 1)) {
    if (activeDaysFilter && !activeDaysFilter.has(d.getDay())) continue;
    const dateStr = getLocalDateStr(d);

    for (let m = 0; m < materiasPorDia; m++) {
      const slotKey = getSkippedSlotKey(dateStr, m);
      if (skippedSlots.has(slotKey) || slotOverrides.has(slotKey) || occupiedSlots.has(slotKey)) {
        simulatedIdx = (simulatedIdx + 1) % seq.length;
        continue;
      }
      const seqItem = seq[simulatedIdx];
      if (!seqItem) break;

      if (!projection[seqItem.discId]) {
        projection[seqItem.discId] = { sessoes: 0, minutos: 0 };
      }
      // 1ª visita ao passo: usa o restante já descontado do estudado. Repetições (ciclos futuros)
      // ainda não foram estudadas, então usam o alvo cheio.
      let remainingMinutes;
      if (!firstVisit.has(seqItem.id)) {
        firstVisit.add(seqItem.id);
        remainingMinutes = remBySeq[seqItem.id]
          ? remBySeq[seqItem.id].remaining
          : Math.max(0, Math.round(Number(seqItem.minutosAlvo) || 0));
      } else {
        remainingMinutes = Math.max(0, Math.round(Number(seqItem.minutosAlvo) || 0));
      }
      if (remainingMinutes <= 0) {
        simulatedIdx = (simulatedIdx + 1) % seq.length;
        continue;
      }
      projection[seqItem.discId].sessoes++;
      projection[seqItem.discId].minutos += remainingMinutes;

      simulatedIdx = (simulatedIdx + 1) % seq.length;
    }
  }

  return projection;
}

export function iniciarEtapaPlanejamento(seqId) {
  if (!state.planejamento || !state.planejamento.sequencia) return;
  const seq = state.planejamento.sequencia.find((s) => s.id === seqId);
  if (!seq) return;
  const targetMinutes = Math.max(0, Math.round(Number(seq.minutosAlvo) || 0));
  const entry = getCycleProgress()[seq.id];
  const studiedMinutes = entry ? entry.usedMins : 0;
  const remainingMinutes = (entry ? entry.remaining : targetMinutes) || targetMinutes;

  if (studiedMinutes > 0 && remainingMinutes > 0 && remainingMinutes < targetMinutes) {
    openPartialPlanningStartPrompt(seq, remainingMinutes, studiedMinutes, targetMinutes);
    return;
  }

  startPlanningSequenceEvent(seq, remainingMinutes);
}

function startPlanningSequenceEvent(seq, durationMinutes, extra = {}) {
  const d = getDisc(seq.discId);

  const evento = {
    id: 'ev_' + uid(),
    titulo: `Estudar ${d?.disc.nome || 'Disciplina'}`,
    data: todayStr(),
    duracao: durationMinutes,
    status: 'agendado',
    tempoAcumulado: 0,
    tipo: 'conteudo',
    discId: seq.discId,
    assId: null,
    habito: null,
    seqId: seq.id,
    criadoEm: new Date().toISOString(),
    ...extra,
  };

  state.eventos.push(evento);
  scheduleSave();

  // Start ticking BEFORE routing
  toggleTimer(evento.id);

  // Switch to Cronometro and let the component render the already active event
  navigate('cronometro');
}

