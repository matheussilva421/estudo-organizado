export function calculateRelevanceWeights(relevanciaDraft) {
  let totalPeso = 0;
  const result = {};

  for (const discId in relevanciaDraft) {
    const r = relevanciaDraft[discId];
    const imp = parseInt(r.importancia, 10) || 3;
    const con = parseInt(r.conhecimento, 10) || 3;

    // Conhecimento 0 -> Fato 6 (muita atenção)
    // Conhecimento 5 -> Fato 1 (pouca atenção)
    const fatorConhecimento = 6 - con;
    const peso = imp * fatorConhecimento;

    result[discId] = { importancia: imp, conhecimento: con, peso };
    totalPeso += peso;
  }

  for (const discId in result) {
    result[discId].percentual = totalPeso > 0 ? (result[discId].peso / totalPeso) * 100 : 0;
  }

  return result;
}

export function generatePlanejamento(draft) {
  const plan = {
    ativo: true,
    tipo: draft.tipo,
    disciplinas: draft.disciplinas,
    relevancia: calculateRelevanceWeights(draft.relevancia),
    horarios: draft.horarios,
    materiasPorDia: parseInt(draft.materiasPorDia, 10) || state.config.materiasPorDia || 3,
    sequencia: [],
    skippedSlots: [],
    slotOverrides: [],
    ciclosCompletos: 0,
    dataInicioCicloAtual: new Date().toISOString(),
  };

  let totalMinutes = 0;

  if (plan.tipo === 'ciclo') {
    const horasSemanais = parseFloat(plan.horarios.horasSemanais) || 0;
    totalMinutes = horasSemanais * 60;
  } else if (plan.tipo === 'semanal') {
    for (let i = 0; i < 7; i++) {
      const hora = plan.horarios.horasPorDia[i];
      if (plan.horarios.diasAtivos.includes(i) && hora && hora.includes(':')) {
        const [hh, mm] = hora.split(':');
        totalMinutes += parseInt(hh, 10) * 60 + parseInt(mm, 10);
      }
    }
  }

  const minSessao = parseInt(plan.horarios.sessaoMin, 10) || 30;
  const maxSessao = parseInt(plan.horarios.sessaoMax, 10) || 120;

  const sortedDiscs = [...plan.disciplinas].sort((a, b) => {
    const wA = plan.relevancia[a]?.peso || 0;
    const wB = plan.relevancia[b]?.peso || 0;
    return wB - wA;
  });

  const pools = [];

  sortedDiscs.forEach((discId) => {
    const perc = plan.relevancia[discId]?.percentual || 0;
    let targetMinutes = Math.round((perc / 100) * totalMinutes);
    if (targetMinutes < minSessao && totalMinutes > 0) targetMinutes = minSessao;

    const discBlocks = [];
    let remaining = targetMinutes;
    while (remaining > 0 && totalMinutes > 0) {
      let block = Math.min(remaining, maxSessao);
      if (block < minSessao && remaining === targetMinutes) {
        block = minSessao;
      } else if (block < minSessao && remaining < targetMinutes) {
        break; // drop remaining tail
      }
      discBlocks.push({
        id: 'seq_' + uid(),
        discId: discId,
        minutosAlvo: block,
        concluido: false,
        status: 'pendente',
      });
      remaining -= block;
    }
    if (discBlocks.length > 0) pools.push(discBlocks);
  });

  // Interleave blocks (Round-Robin) to avoid studying the same subject consecutively
  let hasMore = true;
  while (hasMore) {
    hasMore = false;
    for (let i = 0; i < pools.length; i++) {
      if (pools[i].length > 0) {
        plan.sequencia.push(pools[i].shift());
        hasMore = true;
      }
    }
  }

  state.planejamento = plan;
  resetCicloAndWipeEvents(); // Use the deep wipe when generating completely anew
  return plan;
}

export function deletePlanejamento() {
  document.dispatchEvent(
    new CustomEvent('app:showConfirm', {
      detail: {
        msg: 'Deseja excluir este Planejamento de Estudos? Você precisará criar um novo depois para gerar sequências.',
        onYes: () => {
          state.planejamento = {
            ativo: false,
            tipo: null,
            disciplinas: [],
            relevancia: {},
            horarios: {},
            sequencia: [],
            skippedSlots: [],
            slotOverrides: [],
          };
          resetCicloAndWipeEvents();
          document.dispatchEvent(new Event('app:renderCurrentView'));
        },
        opts: { title: 'Excluir Planejamento' },
      },
    })
  );
}

/**
 * Marca a autoria da última mutação real do plano. O merge de sync usa este
 * timestamp para LWW do planejamento inteiro (sync-center.js) — sem ele, o
 * lado local sempre venceria e mudanças de plano não propagariam entre
 * dispositivos. Chamar APENAS quando o plano de fato muda (nunca em regen de
 * eventos ou salvamentos genéricos, senão todo dispositivo reclama autoria).
 */
export function touchPlanejamento() {
  if (!state.planejamento) return;
  state.planejamento.updatedAt = new Date().toISOString();
}

export function resetCicloAndWipeEvents() {
  if (!state.planejamento) return;
  state.planejamento.skippedSlots = [];
  state.planejamento.slotOverrides = [];
  touchPlanejamento();

  // 1. Wipe all planned cycle events that are not studied yet (including past ones).
  state.eventos = state.eventos.filter((e) => {
    const isCyclePlannedEvent = e.isAutoGenerated || Boolean(e.seqId);
    if (!isCyclePlannedEvent) return true;
    if (e.status === 'estudei' || (e.tempoAcumulado && e.tempoAcumulado > 0)) return true;
    return false; // Remove pending auto generated events completely
  });

  // 2. Reset the sequence conclusion state
  if (state.planejamento.sequencia) {
    state.planejamento.sequencia.forEach((seq) => {
      seq.concluido = false;
      seq.status = 'pendente';
      delete seq.finalizadoEm;
      delete seq.puladaEm;
      delete seq.autoConcluida;
    });
  }

  // 3. Re-inject clean
  syncCicloToEventos();
  scheduleSave();
}

function getActiveStudyDaysFilter(plan = state.planejamento) {
  const diasAtivos = plan?.horarios?.diasAtivos;
  if (!Array.isArray(diasAtivos)) return null;

  const normalizedDays = diasAtivos
    .map((day) => Number(day))
    .filter((day) => Number.isInteger(day) && day >= 0 && day <= 6);

  // No ciclo, os dias são opcionais; lista vazia mantém o comportamento livre (todos os dias).
  if (plan?.tipo === 'ciclo' && normalizedDays.length === 0) return null;

  return new Set(normalizedDays);
}

function isPlanejamentoSeqPending(seq) {
  return getSeqStatus(seq) === 'pendente';
}

function getPendingPlanejamentoSequence(plan = state.planejamento) {
  return (plan?.sequencia || []).filter((seq) => isPlanejamentoSeqPending(seq));
}

/**
 * Soma (em minutos) das sessões concluídas por disciplina, derivada de state.eventos.
 * Fonte única para "minutos estudados por disciplina" — qualquer view deve usar este helper
 * em vez de contadores incrementais persistidos, garantindo que editar/excluir uma sessão
 * reflita automaticamente em todos os lugares.
 * @param {{ since?: string, discId?: string }} [opts]
 *   since  = data mínima 'YYYY-MM-DD' (compara com ev.dataEstudo||ev.data); sem corte por padrão.
 *   discId = se passado, retorna apenas os minutos dessa disciplina (number) em vez do mapa.
 * @returns {Record<string, number> | number} mapa discId->minutos, ou número se discId for dado.
 */
export function getStudiedMinutesByDiscipline(opts = {}) {
  return computeStudiedMinutesByDiscipline(state.eventos, opts);
}

/**
 * Ponto único de leitura do progresso do ciclo: deriva a distribuição por etapa
 * a partir dos eventos concluídos desde o início da rodada atual. Barra da
 * Sequência, Previsão, agendador e reconciliação devem consumir este resultado.
 */
export function getCycleProgress(plan = state.planejamento) {
  const sinceCiclo = (plan?.dataInicioCicloAtual || '').substring(0, 10) || undefined;
  const minutosPorDisc = getStudiedMinutesByDiscipline({ since: sinceCiclo });
  return distributeStudiedAcrossSeq(plan?.sequencia || [], minutosPorDisc);
}

/**
 * Wrapper de estado da reconciliação (núcleo puro em cycle-progress.js):
 * aplica reconcileSequenceWithEvents ao plano ativo com state.eventos e
 * persiste quando algo mudou. Nunca chama touchPlanejamento() — ver núcleo.
 */
export function reconcileCycleProgress(plan = state.planejamento) {
  const result = reconcileSequenceWithEvents(plan, state.eventos);
  if (result.changed) scheduleSave();
  return result;
}

function formatPlanningMinutes(minutes) {
  const total = Math.max(0, Math.round(Number(minutes) || 0));
  const hours = Math.floor(total / 60);
  const mins = total % 60;
  if (hours > 0) return mins > 0 ? `${hours}h ${mins}min` : `${hours}h`;
  return `${mins}min`;
}

function getSkippedSlotKey(data, slotIndex) {
  return `${data || ''}#${Number(slotIndex) || 0}`;
}

function getSkippedSlotKeySet(plan = state.planejamento) {
  return new Set(
    (plan?.skippedSlots || [])
      .filter((slot) => slot?.data)
      .map((slot) => getSkippedSlotKey(slot.data, slot.slotIndex))
  );
}

function getPlanMateriasPorDia(plan = state.planejamento) {
  const planValue = parseInt(plan?.materiasPorDia, 10);
  if (Number.isFinite(planValue) && planValue > 0) return planValue;
  const configValue = parseInt(state.config?.materiasPorDia, 10);
  return Number.isFinite(configValue) && configValue > 0 ? configValue : 3;
}

function getSlotOverrideKey(slot) {
  return getSkippedSlotKey(slot?.data, slot?.slotIndex);
}

/**
 * Slots (data#slotIndex) já consumidos por eventos preservados do Ciclo —
 * sessão estudada ou com tempo acumulado. O agendador não pode re-preencher
 * essas vagas: era o bug da "sessão que volta" (após estudar/apagar, o regen
 * criava um novo pendente no mesmo slot do dia).
 */
function getOccupiedSlotKeySet(eventos = state.eventos) {
  const occupied = new Set();
  for (const ev of eventos || []) {
    if (!ev?.isAutoGenerated || !ev.data) continue;
    if (ev.status !== 'estudei' && !(Number(ev.tempoAcumulado) > 0)) continue;
    if (ev.slotIndex == null || !Number.isInteger(Number(ev.slotIndex))) continue;
    occupied.add(getSkippedSlotKey(ev.data, ev.slotIndex));
  }
  return occupied;
}

function getSlotOverrideMap(plan = state.planejamento) {
  const map = new Map();
  for (const slot of plan?.slotOverrides || []) {
    if (!slot?.data || !Number.isInteger(Number(slot.slotIndex))) continue;
    if (slot.status !== 'perdido' && slot.status !== 'substituido') continue;
    map.set(getSlotOverrideKey(slot), slot);
  }
  return map;
}

function ensureSlotOverrides(plan = state.planejamento) {
  if (!plan) return [];
  if (!Array.isArray(plan.slotOverrides)) plan.slotOverrides = [];
  return plan.slotOverrides;
}

function upsertSlotOverride(slot) {
  const overrides = ensureSlotOverrides();
  const key = getSlotOverrideKey(slot);
  const existingIndex = overrides.findIndex((item) => getSlotOverrideKey(item) === key);
  const now = new Date().toISOString();
  const next = {
    id: existingIndex >= 0 ? overrides[existingIndex].id : 'slot_' + uid(),
    createdAt: existingIndex >= 0 ? overrides[existingIndex].createdAt : now,
    updatedAt: now,
    ...slot,
    slotIndex: Number(slot.slotIndex) || 0,
  };
  if (existingIndex >= 0) overrides[existingIndex] = next;
  else overrides.push(next);
  touchPlanejamento();
  return next;
}

