/**
 * Categoriza eventos do calendário pelo critério de "limpeza do Ciclo".
 * Não muta nada — só inspeciona e conta.
 *
 * Um evento entra em `toDelete` se TODAS forem verdade:
 *  - foi auto-gerado pelo Ciclo (`isAutoGenerated === true`)
 *  - ainda não foi concluído (`status !== 'estudei'`)
 *  - não tem tempo registrado (`tempoAcumulado || 0 === 0`)
 *  - é hoje ou futuro (`data >= todayStr()`)
 *
 * Os demais ficam preservados, particionados nas categorias:
 *  - manual: criado pelo usuário (sem flag `isAutoGenerated`)
 *  - withProgress: tem tempo registrado (qualquer status)
 *  - concluded: status === 'estudei'
 *  - past: ficou no passado (data < hoje) e não tem outra categoria
 */
export function previewClearAutoCicloEvents(reference = state.eventos) {
  const today = todayStr();
  const result = {
    toDelete: [],
    preservedManual: [],
    preservedWithProgress: [],
    preservedConcluded: [],
    preservedPast: [],
  };
  for (const ev of reference || []) {
    if (!ev || typeof ev !== 'object') continue;
    if (ev.status === 'estudei') {
      result.preservedConcluded.push(ev);
      continue;
    }
    if ((Number(ev.tempoAcumulado) || 0) > 0) {
      result.preservedWithProgress.push(ev);
      continue;
    }
    if (!ev.isAutoGenerated) {
      result.preservedManual.push(ev);
      continue;
    }
    const evDate = String(ev.data || '');
    if (evDate && evDate < today) {
      result.preservedPast.push(ev);
      continue;
    }
    result.toDelete.push(ev);
  }
  return result;
}

/**
 * Aplica `previewClearAutoCicloEvents` ao estado, removendo os eventos
 * marcados como `toDelete` e persistindo via scheduleSave. Retorna o resumo
 * (com counts) — útil para a camada de UI mostrar feedback.
 */
export function clearAutoCicloEvents() {
  const preview = previewClearAutoCicloEvents();
  if (preview.toDelete.length === 0) {
    return {
      deleted: 0,
      preservedManual: preview.preservedManual.length,
      preservedWithProgress: preview.preservedWithProgress.length,
      preservedConcluded: preview.preservedConcluded.length,
      preservedPast: preview.preservedPast.length,
    };
  }
  const toDeleteIds = new Set(preview.toDelete.map((ev) => ev.id));
  // Limpa intervalos de timer de eventos a remover (defensivo — eventos sem
  // tempoAcumulado normalmente não têm timer, mas pode haver corrida)
  for (const id of toDeleteIds) {
    if (timerIntervals[id]) {
      clearInterval(timerIntervals[id]);
      delete timerIntervals[id];
    }
  }
  state.eventos = (state.eventos || []).filter((ev) => !toDeleteIds.has(ev.id));
  scheduleSave();
  invalidatePendingRevCache();
  document.dispatchEvent(
    new CustomEvent('app:eventosBulkDeleted', {
      detail: { ids: [...toDeleteIds], reason: 'clear-auto-ciclo' },
    })
  );
  return {
    deleted: toDeleteIds.size,
    preservedManual: preview.preservedManual.length,
    preservedWithProgress: preview.preservedWithProgress.length,
    preservedConcluded: preview.preservedConcluded.length,
    preservedPast: preview.preservedPast.length,
  };
}

