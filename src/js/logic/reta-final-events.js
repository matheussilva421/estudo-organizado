// =============================================
// RETA FINAL — REBUILD PURO DE EVENTOS AUTOMÁTICOS
// Consome blocos já projetados pelo wrapper. Não lê estado, catálogo, relógio,
// DOM, rede ou store; identidade é fornecida por makeId.
// =============================================

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

function isCivilDate(value) {
  if (typeof value !== 'string' || !DATE_RE.test(value)) return false;
  const [year, month, day] = value.split('-').map(Number);
  const leap = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  const days = [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  return year > 0 && month >= 1 && month <= 12 && day >= 1 && day <= days[month - 1];
}

function isPreservedEvent(event) {
  return (
    event?.status === 'estudei' ||
    Number(event?.tempoAcumulado) > 0 ||
    Boolean(event?._timerStart)
  );
}

function importedNotesFields(block) {
  return typeof block?.notas === 'string'
    ? { notas: block.notas, rfNotasAutomaticas: block.notas }
    : {};
}

function refreshRetainedNotes(event, block, now) {
  if (!event?.isAutoGenerated || typeof block?.notas !== "string") return false;
  const automatic = event.rfNotasAutomaticas;
  if (typeof automatic === "string" && event.notas === automatic) {
    if (event.notas === block.notas) return false;
    event.notas = block.notas;
    event.rfNotasAutomaticas = block.notas;
    if (typeof now === "string" && now) event.updatedAt = now;
    return true;
  }
  if (automatic !== undefined) return false;
  if (event.notas !== undefined) return false;
  event.notas = block.notas;
  event.rfNotasAutomaticas = block.notas;
  if (typeof now === "string" && now) event.updatedAt = now;
  return true;
}

function effectiveDate(block) {
  return Object.prototype.hasOwnProperty.call(block, 'dataEfetiva') ? block.dataEfetiva : block.data;
}

function isSchedulable(block, today) {
  if (!block?.id || block.arquivado === true || block.status !== 'pendente') return false;
  if (
    block.naoAlocado === true ||
    block.alocacao === 'nao_alocada' ||
    block.alocacao === 'nao_alocado' ||
    ['nao_alocado', 'nao_coberto', 'sem_data'].includes(block.categoriaTemporal)
  ) {
    return false;
  }

  const date = effectiveDate(block);
  return isCivilDate(date) && date >= today;
}

function obsoleteReason(event, block, today, occupiedBlockIds) {
  if (!block) return 'bloco_inexistente';
  if (block.arquivado === true) return 'bloco_arquivado';
  if (block.status !== 'pendente') return 'bloco_nao_pendente';
  if (
    block.naoAlocado === true ||
    block.alocacao === 'nao_alocada' ||
    block.alocacao === 'nao_alocado' ||
    ['nao_alocado', 'nao_coberto', 'sem_data'].includes(block.categoriaTemporal)
  ) {
    return 'bloco_fora_da_agenda';
  }

  const date = effectiveDate(block);
  if (!isCivilDate(date)) return 'data_efetiva_invalida';
  if (date < today) return 'data_passada';
  if (date !== event.data) return 'data_divergente';
  if (Math.round(Number(event.duracao) || 0) !== Math.round(Number(block.minutos) || 0)) {
    return 'duracao_divergente';
  }
  if (occupiedBlockIds.has(block.id)) return 'ligacao_duplicada';
  return null;
}

function manualEventNotes(event) {
  if (typeof event?.notas !== 'string') return undefined;
  if (
    typeof event.rfNotasAutomaticas === 'string' &&
    event.notas === event.rfNotasAutomaticas
  ) {
    return undefined;
  }
  return event.notas;
}

/**
 * Reconstrói eventos automáticos para blocos pendentes na agenda efetiva.
 * `plan.retaFinal.blocos` deve conter projeções quando a versão do plano as
 * utiliza (`dataEfetiva`), ou blocos v1 após o rollover legado.
 *
 * @param {object} plan plano `reta_final`
 * @param {object[]} events eventos atuais
 * @param {{ today: string, makeId: () => string }} options dependências determinísticas
 * @returns {{ events: object[], changed: boolean, diagnostics: object }}
 */
export function rebuildRetaFinalAutoEvents(plan, events, { today, makeId, now } = {}) {
  const sourceEvents = Array.isArray(events) ? events : [];
  const diagnostics = { removed: [], created: [], skipped: [] };
  let updated = 0;
  const blocks = plan?.retaFinal?.blocos;
  if (plan?.ativo === false || plan?.tipo !== 'reta_final' || !Array.isArray(blocks) || !isCivilDate(today)) {
    if (!isCivilDate(today)) diagnostics.skipped.push({ reason: 'data_referencia_invalida' });
    return { events: sourceEvents, changed: false, diagnostics };
  }

  const blockById = new Map();
  for (const block of blocks) {
    if (block?.id) blockById.set(block.id, block);
  }

  // Sessão real, vínculo manual ou auto em status não pendente ocupam o bloco.
  // O rebuild não remove evidência histórica nem cria segunda ligação.
  const occupiedBlockIds = new Set();
  for (const event of sourceEvents) {
    if (!event?.rfBlocoId) continue;
    if (!event.isAutoGenerated || isPreservedEvent(event) || event.status !== 'agendado') {
      occupiedBlockIds.add(event.rfBlocoId);
    }
  }

  const retained = [];
  for (const event of sourceEvents) {
    if (
      !event?.rfBlocoId ||
      event.isAutoGenerated !== true ||
      isPreservedEvent(event) ||
      event.status !== 'agendado'
    ) {
      retained.push(event);
      continue;
    }

    const block = blockById.get(event.rfBlocoId);
    const reason = obsoleteReason(event, block, today, occupiedBlockIds);
    // Um segundo auto com anotação é evidência de conteúdo do usuário ou de
    // importação anterior; preservar é preferível a apagar texto por dedupe.
    if (
      reason === 'ligacao_duplicada' &&
      (typeof event.notas === 'string' ||
        event.rfNotasAutomaticas !== undefined)
    ) {
      retained.push(event);
      continue;
    }
    const scheduleMismatch =
      reason === 'data_divergente' || reason === 'duracao_divergente';
    const hasNotes =
      typeof event.notas === 'string' ||
      event.rfNotasAutomaticas !== undefined;
    if (scheduleMismatch && block && hasNotes) {
      const nextData = effectiveDate(block);
      const nextDuration = Math.max(0, Math.round(Number(block.minutos) || 0));
      if (event.data !== nextData || event.duracao !== nextDuration) {
        event.data = nextData;
        event.duracao = nextDuration;
        updated++;
      }
      if (refreshRetainedNotes(event, block, now)) updated++;
      occupiedBlockIds.add(event.rfBlocoId);
      retained.push(event);
      continue;
    }
    if (reason) {
      const manualNotes = manualEventNotes(event);
      diagnostics.removed.push({
        eventId: event.id ?? null,
        blocoId: event.rfBlocoId,
        reason,
        ...(manualNotes === undefined
          ? {}
          : {
              notas: manualNotes,
              rfNotasAutomaticas:
                typeof event.rfNotasAutomaticas === 'string'
                  ? event.rfNotasAutomaticas
                  : null
            })
      });
      continue;
    }

    occupiedBlockIds.add(event.rfBlocoId);
    if (refreshRetainedNotes(event, block, now)) updated++;
    retained.push(event);
  }

  const retainedBlockIds = new Set(retained.map((event) => event?.rfBlocoId).filter(Boolean));
  const created = [];
  for (const block of blocks) {
    if (!isSchedulable(block, today) || retainedBlockIds.has(block.id)) continue;
    if (typeof makeId !== 'function') {
      diagnostics.skipped.push({
        blocoId: block.id,
        reason: 'make_id_ausente'
      });
      continue;
    }

    const id = makeId();
    if (typeof id !== 'string' || !id) {
      diagnostics.skipped.push({
        blocoId: block.id,
        reason: 'make_id_invalido'
      });
      continue;
    }

    const primeiroTopico = (block.topicos || [])[0] || null;
    const event = {
      id: 'autorf_' + id,
      titulo: '',
      data: effectiveDate(block),
      duracao: Math.max(0, Math.round(Number(block.minutos) || 0)),
      status: 'agendado',
      tempoAcumulado: 0,
      tipo: 'conteudo',
      discId: block.discId || null,
      assId: primeiroTopico?.assId || null,
      aulaId: primeiroTopico?.aulaId || null,
      habito: null,
      ...importedNotesFields(block),
      rfBlocoId: block.id,
      isAutoGenerated: true
    };
    created.push(event);
    retainedBlockIds.add(block.id);
    diagnostics.created.push({ eventId: event.id, blocoId: block.id });
  }

  const changed =
    diagnostics.removed.length > 0 || created.length > 0 || updated > 0;
  return {
    events: changed ? [...retained, ...created] : sourceEvents,
    changed,
    diagnostics
  };
}

/**
 * Antes de um evento automático ser removido (bloco arquivado ou fora da
 * agenda), devolve ao bloco a nota manual escrita no evento. Nunca sobrescreve
 * uma nota manual já existente no bloco; só substitui texto que ainda é o
 * espelho automático da importação.
 */
export function carryRemovedAutoNotesToBlocks(blocks, removed) {
  let changed = 0;
  if (!Array.isArray(blocks) || !Array.isArray(removed)) return changed;
  const byId = new Map();
  for (const block of blocks) {
    if (block?.id) byId.set(block.id, block);
  }
  for (const item of removed) {
    if (!item?.blocoId || typeof item.notas !== 'string') continue;
    const block = byId.get(item.blocoId);
    if (!block || block.notas === item.notas) continue;
    const canReplace =
      typeof block.notas !== 'string' ||
      (typeof item.rfNotasAutomaticas === 'string' &&
        block.notas === item.rfNotasAutomaticas);
    if (!canReplace) continue;
    block.notas = item.notas;
    changed += 1;
  }
  return changed;
}
