import { describe, expect, it, vi } from 'vitest';
import { rebuildRetaFinalAutoEvents } from '../../src/js/logic/reta-final-events.js';

const HOJE = '2026-10-20';

function bloco(overrides = {}) {
  return {
    id: 'rf_1',
    data: HOJE,
    dataEfetiva: HOJE,
    minutos: 90,
    status: 'pendente',
    discId: 'disc_1',
    topicos: [{ assId: 'ass_1', aulaId: null }],
    ...overrides
  };
}

function plano(blocos) {
  return {
    ativo: true,
    tipo: 'reta_final',
    retaFinal: { dataFinal: '2026-10-31', blocos }
  };
}

function autoEvento(overrides = {}) {
  return {
    id: 'autorf_old',
    titulo: 'Estudar Direito Penal',
    data: HOJE,
    duracao: 90,
    status: 'agendado',
    tempoAcumulado: 0,
    tipo: 'conteudo',
    discId: 'disc_1',
    assId: 'ass_1',
    aulaId: null,
    rfBlocoId: 'rf_1',
    isAutoGenerated: true,
    ...overrides
  };
}

function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.values(value).forEach(deepFreeze);
    Object.freeze(value);
  }
  return value;
}

function rebuild(planValue, eventsValue, makeId = () => 'new') {
  return rebuildRetaFinalAutoEvents(planValue, eventsValue, {
    today: HOJE,
    makeId
  });
}

describe('rebuildRetaFinalAutoEvents', () => {
  it('remove auto eventos obsoletos sem afetar eventos manuais', () => {
    const events = [
      autoEvento({ id: 'autorf_missing', rfBlocoId: 'rf_missing' }),
      autoEvento({ id: 'autorf_completed', rfBlocoId: 'rf_completed' }),
      autoEvento({
        id: 'autorf_past',
        rfBlocoId: 'rf_past',
        data: '2026-10-19'
      }),
      { id: 'manual', rfBlocoId: 'rf_missing', isAutoGenerated: false }
    ];
    const result = rebuild(
      plano([
        bloco({ id: 'rf_completed', status: 'concluido' }),
        bloco({ id: 'rf_past', dataEfetiva: '2026-10-19', data: '2026-10-19' })
      ]),
      events
    );

    expect(result.events).toEqual([{ id: 'manual', rfBlocoId: 'rf_missing', isAutoGenerated: false }]);
    expect(result.changed).toBe(true);
  });

  it('preserva auto evento não pendente sem evidência quando o bloco não existe', () => {
    const completedWithoutEvidence = autoEvento({
      id: 'autorf_concluido',
      rfBlocoId: 'rf_inexistente',
      status: 'concluido',
      tempoAcumulado: 0
    });
    const events = [completedWithoutEvidence];
    const snapshot = structuredClone(completedWithoutEvidence);

    const result = rebuild(plano([]), events);

    expect(result.events).toBe(events);
    expect(result.events[0]).toBe(completedWithoutEvidence);
    expect(completedWithoutEvidence).toEqual(snapshot);
    expect(result.changed).toBe(false);
    expect(result.diagnostics.removed).toEqual([]);
  });

  it('evento auto retido com status não pendente impede uma ligação duplicada', () => {
    const retainedEvent = autoEvento({
      id: 'autorf_concluido',
      status: 'concluido',
      tempoAcumulado: 0,
      data: '2026-10-18'
    });
    const events = [retainedEvent];
    const makeId = vi.fn(() => 'must-not-be-used');

    const result = rebuild(plano([bloco()]), events, makeId);

    expect(result.events).toBe(events);
    expect(result.changed).toBe(false);
    expect(makeId).not.toHaveBeenCalled();
    expect(result.events.filter((event) => event.rfBlocoId === 'rf_1')).toHaveLength(1);
  });

  it('reserva o bloco de evento não pendente e remove o agendado duplicado', () => {
    const completedEvent = autoEvento({
      id: 'autorf_concluido',
      status: 'concluido',
      tempoAcumulado: 0
    });
    const scheduledDuplicate = autoEvento({ id: 'autorf_agendado' });
    const events = [completedEvent, scheduledDuplicate];
    const makeId = vi.fn(() => 'must-not-be-used');

    const result = rebuild(plano([bloco()]), events, makeId);

    expect(result.events).toHaveLength(1);
    expect(result.events[0]).toBe(completedEvent);
    expect(result.changed).toBe(true);
    expect(makeId).not.toHaveBeenCalled();
    expect(result.events.filter((event) => event.rfBlocoId === 'rf_1')).toHaveLength(1);
    expect(result.diagnostics.removed).toEqual([
      {
        eventId: 'autorf_agendado',
        blocoId: 'rf_1',
        reason: 'ligacao_duplicada'
      }
    ]);
  });

  it('preserva evento que acumulou exatamente um minuto', () => {
    const partial = autoEvento({ tempoAcumulado: 60 });
    const events = [partial];

    const result = rebuild(plano([bloco()]), events);

    expect(result.events).toBe(events);
    expect(result.events[0]).toBe(partial);
    expect(result.changed).toBe(false);
  });

  it('preserva integralmente título, datas e dados de evento estudado', () => {
    const studied = autoEvento({
      titulo: 'Título escolhido pelo usuário',
      data: '2026-10-18',
      dataEstudo: '2026-10-18',
      duracao: 47,
      status: 'estudei',
      tempoAcumulado: 0,
      questoes: { total: 12, corretas: 9 },
      revisoes: [{ data: '2026-10-19', tipo: 'curta' }]
    });
    const snapshot = structuredClone(studied);
    const events = [studied];

    const result = rebuild(plano([bloco({ data: '2026-10-25', dataEfetiva: '2026-10-25', minutos: 120 })]), events);

    expect(result.events).toBe(events);
    expect(result.events[0]).toBe(studied);
    expect(studied).toEqual(snapshot);
    expect(result.changed).toBe(false);
  });

  it('remove e recria auto evento quando a projeção move o bloco', () => {
    const oldEvent = autoEvento({ data: '2026-10-20', duracao: 90 });
    const manual = { id: 'manual', isAutoGenerated: false };

    const result = rebuild(
      plano([bloco({ data: '2026-10-22', dataEfetiva: '2026-10-22', minutos: 45 })]),
      [oldEvent, manual],
      () => 'moved'
    );

    expect(result.events.map((event) => event.id)).toEqual(['manual', 'autorf_moved']);
    expect(result.events[1].id).toMatch(/^autorf_/);
    expect(result.events[1]).toMatchObject({
      data: '2026-10-22',
      duracao: 45,
      status: 'agendado',
      rfBlocoId: 'rf_1',
      isAutoGenerated: true
    });
    expect(result.changed).toBe(true);
  });

  it('não ressuscita bloco arquivado que ainda está marcado como pendente', () => {
    const events = [autoEvento()];

    const result = rebuild(plano([bloco({ arquivado: true })]), events);

    expect(result.events).toEqual([]);
    expect(result.changed).toBe(true);
  });

  it('não agenda bloco indisponível ou explicitamente não alocado', () => {
    const events = [];

    const result = rebuild(
      plano([
        bloco({ id: 'rf_unallocated', naoAlocado: true, dataEfetiva: null }),
        bloco({
          id: 'rf_outside',
          categoriaTemporal: 'nao_coberto',
          dataEfetiva: '2026-10-25'
        })
      ]),
      events
    );

    expect(result.events).toBe(events);
    expect(result.changed).toBe(false);
  });

  it('não cria segunda ligação e retorna o array original na chamada idempotente', () => {
    const first = rebuild(plano([bloco()]), []);
    const second = rebuild(plano([bloco()]), first.events, () => 'must-not-be-used');

    expect(first.changed).toBe(true);
    expect(second.changed).toBe(false);
    expect(second.events).toBe(first.events);
    expect(second.events.filter((event) => event.rfBlocoId === 'rf_1')).toHaveLength(1);
  });

  it('não altera os objetos de entrada ao remover e materializar eventos', () => {
    const inputPlan = deepFreeze(plano([bloco({ data: '2026-10-22', dataEfetiva: '2026-10-22' })]));
    const inputEvents = deepFreeze([autoEvento()]);
    const planSnapshot = structuredClone(inputPlan);
    const eventsSnapshot = structuredClone(inputEvents);

    const result = rebuild(inputPlan, inputEvents, () => 'immutable');

    expect(result.events).not.toBe(inputEvents);
    expect(inputPlan).toEqual(planSnapshot);
    expect(inputEvents).toEqual(eventsSnapshot);
  });

  it('usa apenas dependências injetadas e pode rodar sem estado, DOM, rede ou relógio', () => {
    const forbidden = new Proxy(
      {},
      {
        get(_target, property) {
          throw new Error(`dependência global acessada: ${String(property)}`);
        }
      }
    );
    const names = ['Date', 'document', 'window', 'state', 'store', 'fetch', 'localStorage', 'setTimeout'];
    const originalRandom = Math.random;
    Math.random = () => {
      throw new Error('Math.random não deve ser usado');
    };
    names.forEach((name) => vi.stubGlobal(name, forbidden));

    let result;
    try {
      result = rebuild(plano([bloco()]), [], () => 'pure');
    } finally {
      vi.unstubAllGlobals();
      Math.random = originalRandom;
    }

    expect(result.events[0].id).toBe('autorf_pure');
    expect(result.events[0].data).toBe(HOJE);
  });
});
